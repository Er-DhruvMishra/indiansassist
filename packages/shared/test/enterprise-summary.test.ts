/**
 * Phase E sections 5.2e, 5.3, 5.5: `normaliseSummaryOutput`, `renderSummaryInput`, the input size cap with middle
 * trimming, `aiAckText` for both scopes, the transcript notices and `summaryOutputSha256`.
 */
import { describe, expect, it } from 'vitest';
import {
  LIMITS,
  SUMMARY_PROMPT_VERSION,
  aiAckText,
  canonicalJsonBytes,
  capSummaryInput,
  normaliseSummaryOutput,
  renderSummaryInput,
  sessionSummaryOutputSchema,
  sha256Hex,
  summaryOutputSha256,
  summaryPromptInputSchema,
  summaryTranscriptNotice,
  type SessionSummaryOutput,
  type SummaryPromptInput,
} from '../src/index.js';

const TS = '2026-11-02T10:00:00.000Z';
const output: SessionSummaryOutput = {
  summary: 'The technician cleared the print queue.',
  outcome: 'resolved',
  actionsTaken: ['Restarted the spooler'],
  issuesFound: ['Stuck print job'],
  followUps: [],
  ticketNote: 'Cleared the print queue and restarted the spooler.',
};

function input(events: number, messages: number, textLen = 200): SummaryPromptInput {
  return {
    v: 1,
    promptVersion: SUMMARY_PROMPT_VERSION,
    session: { tier: 'p1_browser', startedAt: TS, endedAt: TS, durationMs: 60_000, endReason: 'assist_ended', path: 'p2p', recorded: false, unattended: null },
    events: Array.from({ length: events }, (_, i) => ({ t: TS, actor: 'technician' as const, text: `event ${i} ${'e'.repeat(Math.min(textLen, 280))}` })),
    transcript:
      messages > 0
        ? {
            messages: Array.from({ length: messages }, (_, i) => ({ from: i % 2 ? ('user' as const) : ('technician' as const), at: TS, text: `message ${i} ${'m'.repeat(textLen)}` })),
            playbookOutputs: [{ playbook: 'Clear print queue', exit: 0, stdoutTail: 'ok', stderrTail: '' }],
          }
        : null,
    truncated: false,
  };
}

describe('aiAckText (section 5.2e)', () => {
  it('in_geo names the United States and the refusal outcome', () => {
    expect(aiAckText('in_geo', 'Acme IT', 'India (Mumbai)')).toBe(
      "I confirm that session summaries for Acme IT will be generated by Anthropic (Claude) with inference requested in the United States. Session content, after redaction, will leave IndiansAssist's infrastructure. If the model declines a request, no summary is produced for that session.",
    );
  });
  it('outside_region names the fallback model and the region', () => {
    expect(aiAckText('outside_region', 'Acme IT', 'India (Mumbai)')).toBe(
      "I confirm that session summaries for Acme IT will be generated by Anthropic (Claude), or by a fallback model Anthropic selects when the first model declines, and that inference may run outside India (Mumbai). Session content, after redaction, will leave the India (Mumbai) region and IndiansAssist's infrastructure.",
    );
  });
});

describe('summaryTranscriptNotice (section 5.3a)', () => {
  it('names who will read the chat for each provider and scope', () => {
    expect(summaryTranscriptNotice('local', null, 'India (Mumbai)')).toBe(
      "This chat may be summarised for the support record by an automated assistant that runs inside IndiansAssist's India (Mumbai) infrastructure. Email addresses, phone numbers and recognised secrets are removed first.",
    );
    expect(summaryTranscriptNotice('anthropic', 'in_geo', 'US East')).toBe(
      "This chat may be summarised for the support record by Anthropic's Claude, with processing in the United States. Email addresses, phone numbers and recognised secrets are removed first.",
    );
    expect(summaryTranscriptNotice('anthropic', 'outside_region', 'EU (Frankfurt)')).toBe(
      "This chat may be summarised for the support record by Anthropic's Claude, with processing that may happen outside EU (Frankfurt). Email addresses, phone numbers and recognised secrets are removed first.",
    );
  });
  it('has no notice for none or an unacknowledged anthropic', () => {
    expect(() => summaryTranscriptNotice('none', null, 'x')).toThrow(RangeError);
    expect(() => summaryTranscriptNotice('anthropic', null, 'x')).toThrow(RangeError);
  });
});

describe('renderSummaryInput', () => {
  it('wraps the canonical JSON of the input in a delimiter after a fixed preamble', () => {
    const i = input(2, 1);
    const text = renderSummaryInput(i);
    const json = text.split('\n<session_record>\n')[1]!.split('\n</session_record>')[0]!;
    expect(JSON.parse(json)).toEqual(i);
    expect(text.startsWith('Write the support record')).toBe(true);
    expect(renderSummaryInput(i)).toBe(text);
  });
});

describe('capSummaryInput (section 5.3)', () => {
  it('leaves a small input untouched', () => {
    const i = input(5, 5);
    expect(capSummaryInput(i)).toBe(i);
  });
  it('drops transcript messages from the middle first, keeping the first and last 50', () => {
    const i = input(10, 500, 1000);
    const out = capSummaryInput(i);
    expect(canonicalJsonBytes(out).length).toBeLessThanOrEqual(LIMITS.summaryInputMaxBytes);
    expect(out.truncated).toBe(true);
    expect(out.events).toHaveLength(10);
    const msgs = out.transcript!.messages;
    expect(msgs.length).toBeLessThan(500);
    expect(msgs.length).toBeGreaterThanOrEqual(100);
    expect(msgs[0]!.text.startsWith('message 0 ')).toBe(true);
    expect(msgs[49]!.text.startsWith('message 49 ')).toBe(true);
    expect(msgs.at(-1)!.text.startsWith('message 499 ')).toBe(true);
    expect(msgs.at(-50)!.text.startsWith('message 450 ')).toBe(true);
    expect(i.transcript!.messages).toHaveLength(500);
    expect(summaryPromptInputSchema.safeParse(out).success).toBe(true);
  });
  it('then drops events from the middle when the messages are down to 100', () => {
    const i = input(400, 100, 700);
    const out = capSummaryInput(i);
    expect(canonicalJsonBytes(out).length).toBeLessThanOrEqual(LIMITS.summaryInputMaxBytes);
    expect(out.transcript!.messages).toHaveLength(100);
    expect(out.events.length).toBeLessThan(400);
    expect(out.events[0]!.text.startsWith('event 0 ')).toBe(true);
    expect(out.events.at(-1)!.text.startsWith('event 399 ')).toBe(true);
  });
  it('honours a smaller cap', () => {
    const out = capSummaryInput(input(400, 0), 20_000);
    expect(canonicalJsonBytes(out).length).toBeLessThanOrEqual(20_000);
    expect(out.truncated).toBe(true);
  });
});

describe('normaliseSummaryOutput (section 5.5)', () => {
  it('passes a valid object through unchanged', () => {
    expect(normaliseSummaryOutput(output)).toEqual({ output, normalised: false });
  });
  it('cuts over-long strings at a word boundary with an ellipsis and over-long arrays at their limit', () => {
    const long = Array.from({ length: 400 }, (_, i) => `word${i}`).join(' ');
    const r = normaliseSummaryOutput({
      ...output,
      summary: long,
      actionsTaken: Array.from({ length: 30 }, (_, i) => `step ${i}`),
      issuesFound: ['x'.repeat(400)],
      ticketNote: long + long + long,
    })!;
    expect(r.normalised).toBe(true);
    expect(r.output.summary.length).toBeLessThanOrEqual(1500);
    expect(r.output.summary.endsWith('…')).toBe(true);
    expect(r.output.summary.slice(0, -1)).toMatch(/word\d+$/);
    expect(r.output.actionsTaken).toHaveLength(25);
    expect(r.output.issuesFound[0]!.length).toBe(300);
    expect(r.output.ticketNote.length).toBeLessThanOrEqual(6000);
    expect(sessionSummaryOutputSchema.safeParse(r.output).success).toBe(true);
  });
  it('drops unknown keys and empty entries, maps an unknown outcome to unknown', () => {
    const r = normaliseSummaryOutput({ ...output, outcome: 'great', extra: 1, followUps: ['', 7, 'Call back'] })!;
    expect(r.normalised).toBe(true);
    expect(r.output.outcome).toBe('unknown');
    expect(r.output.followUps).toEqual(['Call back']);
    expect('extra' in r.output).toBe(false);
  });
  it('is null when the value is not the object at all', () => {
    for (const v of [null, 'text', 42, [output], {}, { ...output, summary: '' }, { ...output, ticketNote: 3 }])
      expect(normaliseSummaryOutput(v)).toBeNull();
  });
});

describe('summaryOutputSha256', () => {
  it('is the sha256 of the canonical JSON and independent of key order', () => {
    expect(summaryOutputSha256(output)).toBe(sha256Hex(canonicalJsonBytes(output)));
    const reordered = Object.fromEntries(Object.entries(output).reverse()) as SessionSummaryOutput;
    expect(summaryOutputSha256(reordered)).toBe(summaryOutputSha256(output));
  });
});
