// Phase E smoke flow of stream ai (docs/specs/phase-e-contracts.md sections 5, 15.4), run by scripts/smoke-e.mjs.
// A fake local chat-completions server runs in this process (no model, nothing leaves the machine); the api under
// test must be started with AI_LOCAL_ENDPOINTS=<its default region>=http://127.0.0.1:<SMOKE_AI_MODEL_PORT>.
//
// Steps: the fake model server; a throwaway org (example.test address); capabilities report `local`; the policy is
// set to the local provider with the transcript; a live p1 session (Assist + Desk sockets); the transcript upload
// (a planted address must come back redacted); the session ended; an on-demand summary generated by the sweeper and
// chained; the fake saw only redacted text; an edit as version 2; then, when the tickets stream is present and the
// api allows loopback egress, a webhook push of the summary (otherwise reported as not run).
//
// Env: SMOKE_AI_MODEL_PORT (default 4193), SMOKE_AI_READY_MS (default 45000: the sweeper runs every 10 s).

import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';
import { signalUrlFor } from './http.mjs';
import { check, eq } from './runner.mjs';
import { SignalClient } from './ws-client.mjs';

const PLANTED = 'smoke.user@example.test';

const ANSWER = {
  summary: 'The technician confirmed the printer queue was cleared during the smoke session.',
  outcome: 'resolved',
  actionsTaken: ['Cleared the print queue'],
  issuesFound: ['A stuck print job'],
  followUps: [],
  ticketNote: 'Cleared the print queue; printing works again.',
};

/** The in-process fake model server (chat completions) and webhook receiver. */
function startFake(port) {
  const seen = { completions: [], hooks: [] };
  const server = createServer((req, res) => {
    let body = '';
    req.on('data', (c) => (body += c.toString('utf8')));
    req.on('end', () => {
      if (req.method === 'POST' && req.url === '/v1/chat/completions') {
        seen.completions.push(body);
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(
          JSON.stringify({
            model: 'smoke-fake-model',
            choices: [{ index: 0, message: { role: 'assistant', content: JSON.stringify(ANSWER) }, finish_reason: 'stop' }],
            usage: { prompt_tokens: 100, completion_tokens: 40 },
          }),
        );
        return;
      }
      if (req.method === 'POST' && req.url?.startsWith('/hook')) {
        seen.hooks.push(body);
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ id: `smoke-${seen.hooks.length}`, url: null }));
        return;
      }
      res.writeHead(404);
      res.end();
    });
  });
  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => resolve({ server, seen }));
  });
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** @param {import('./runner.mjs').Runner} run */
export async function flowSteps(run, ctx) {
  const { api, cfg, state } = ctx;
  const T = cfg.timeoutMs;
  const port = Number(process.env.SMOKE_AI_MODEL_PORT || 4193);
  const readyMs = Number(process.env.SMOKE_AI_READY_MS || 45_000);
  let fake = null;

  try {
    await run.step('ai: fake local model server', async () => {
      fake = await startFake(port);
      return `http://127.0.0.1:${port}`;
    });

    await run.step('ai: signup a throwaway org', async () => {
      const wk = await api.expect('GET', '/.well-known/indiansassist.json');
      cfg.webOrigin ??= new URL(wk.join).origin;
      api.origin = cfg.webOrigin;
      const id = `smoke-ai-${Date.now().toString(36)}`;
      const r = await api.expect('POST', '/api/v1/auth/signup', { orgName: `Smoke AI ${id}`, name: 'Smoke Admin', email: `${id}@example.test`, password: 'correct horse battery' }, [201]);
      state.user = r.user;
      state.org = r.org;
      return `org ${r.org.slug}`;
    });

    await run.step('ai: GET /ai/capabilities reports the local provider', async () => {
      const caps = await api.expect('GET', '/api/v1/ai/capabilities');
      state.region = caps.region;
      check(caps.local === true, `the api serves no local provider for ${caps.region}: start it with AI_LOCAL_ENDPOINTS=${caps.region}=http://127.0.0.1:${port}`);
      return `region ${caps.region}`;
    });

    await run.step('ai: PATCH ai-policy local + transcript, chained', async () => {
      const p = await api.expect('PATCH', '/api/v1/orgs/current/ai-policy', { provider: 'local', autoSummarize: false, includeTranscript: true });
      eq(p.provider, 'local', 'provider');
      eq(p.includeTranscript, true, 'includeTranscript');
      eq(p.anthropicAck, null, 'anthropicAck');
      const ack = await api.request('PATCH', '/api/v1/orgs/current/ai-policy', { provider: 'anthropic' });
      check(ack.status === 400 || ack.status === 409, `anthropic without an acknowledgement must be refused (got ${ack.status})`);
    });

    await run.step('ai: a live p1 session (token, assist + desk sockets, knock, accept, consent)', async () => {
      const tok = await api.expect('POST', '/api/v1/tokens', { tier: 'p1_browser', typ: 'one_time' }, [201]);
      const signalUrl = cfg.signalUrl ?? signalUrlFor(cfg.apiUrl);
      const assist = new SignalClient('assist', signalUrl, { Origin: cfg.webOrigin, Cookie: api.cookie });
      ctx.sockets.push(assist);
      await assist.open(T);
      assist.send({ t: 'assist.hello' });
      await assist.next('assist.hello.ok', T);
      const desk = new SignalClient('desk', signalUrl, { Origin: cfg.webOrigin });
      ctx.sockets.push(desk);
      await desk.open(T);
      desk.send({ t: 'desk.hello', token: tok.compact, deskLabel: 'Smoke AI Desk' });
      await desk.next('desk.hello.ok', T);
      desk.send({ t: 'desk.knock' });
      const knock = await desk.next('knock.ok', T);
      state.sessionId = knock.sessionId;
      await assist.next((m) => m.t === 'assist.knock' && m.sessionId === knock.sessionId, T, 'assist.knock');
      assist.send({ t: 'assist.accept', sessionId: knock.sessionId });
      await assist.next('session.created', T);
      await desk.next('session.created', T);
      desk.send({ t: 'desk.consent', state: 'granted', surface: 'monitor' });
      const ok = await desk.next('consent.ok', T);
      eq(ok.state, 'active', 'consent.ok state');
      return `session ${state.sessionId}`;
    });

    await run.step('ai: POST summary-input (the console transcript) -> 202, redacted', async () => {
      const notice = new Date(Date.now() - 2000).toISOString();
      const r = await api.expect(
        'POST',
        `/api/v1/sessions/${state.sessionId}/summary-input`,
        {
          noticeSentAt: notice,
          noticeProvider: 'local',
          messages: [
            { from: 'technician', at: notice, text: 'This chat may be summarised for the support record.' },
            { from: 'user', at: new Date().toISOString(), text: `The printer queue is stuck; reach me at ${PLANTED}.` },
          ],
          playbookOutputs: [],
          consoleRedaction: 'redact-v1',
        },
        [202],
      );
      check(/^[0-9a-f]{64}$/.test(r.sha256), 'sha256');
      check(r.redactions.email >= 1, 'the planted address was not counted as redacted');
      return `${r.redactions.email} email redacted`;
    });

    await run.step('ai: end the session', async () => {
      const s = await api.expect('POST', `/api/v1/sessions/${state.sessionId}/end`, {});
      eq(s.state, 'ended', 'state');
    });

    await run.step('ai: POST summary -> 202 pending (on demand)', async () => {
      const r = await api.expect('POST', `/api/v1/sessions/${state.sessionId}/summary`, {}, [202]);
      eq(r.summary.state, 'pending', 'state');
      eq(r.summary.trigger, 'on_demand', 'trigger');
      const again = await api.request('POST', `/api/v1/sessions/${state.sessionId}/summary`, {});
      eq(again.json?.error?.code, 'summary_running', 'a second request');
    });

    await run.step('ai: the sweeper generates it with the fake model (ready)', async () => {
      const deadline = Date.now() + readyMs;
      for (;;) {
        const l = await api.expect('GET', `/api/v1/sessions/${state.sessionId}/summary`);
        const v = l.latest;
        if (v?.state === 'ready') {
          eq(v.servedModel, 'smoke-fake-model', 'servedModel');
          eq(v.transcriptIncluded, true, 'transcriptIncluded');
          eq(v.inferenceGeo, state.region, 'inferenceGeo');
          eq(v.output.summary, ANSWER.summary, 'output.summary');
          state.summary = v;
          return `version ${v.version} after ${v.attempts} attempt(s)`;
        }
        check(v?.state !== 'failed', `the summary failed: ${v?.cause}`);
        check(Date.now() < deadline, `not ready within ${readyMs} ms (state ${v?.state})`);
        await sleep(1000);
      }
    });

    await run.step('ai: the fake model received only redacted text', async () => {
      check(fake.seen.completions.length >= 1, 'the fake model was never called');
      const body = fake.seen.completions.at(-1);
      check(!body.includes(PLANTED), 'the planted address reached the model');
      check(body.includes('[email-'), 'no email placeholder in the model input');
      const req = JSON.parse(body);
      eq(req.response_format?.json_schema?.name, 'ia_session_summary', 'response_format name');
      eq(req.stream, false, 'stream');
    });

    await run.step('ai: the chain records the transcript, the request and the generation', async () => {
      const a = await api.expect('GET', `/api/v1/sessions/${state.sessionId}/audit`);
      const actions = a.items.map((e) => e.action);
      for (const want of ['summary.transcript_received', 'summary.requested', 'summary.generated']) check(actions.includes(want), `missing ${want}`);
      const gen = a.items.find((e) => e.action === 'summary.generated');
      eq(gen.data.sha256, state.summary.sha256, 'summary.generated sha256');
      check(a.integrity.ok === true, 'session chain integrity');
      check(!JSON.stringify(a.items).includes(PLANTED), 'the planted address is in the chain');
    });

    await run.step('ai: PUT summary (technician edit) -> version 2, chained', async () => {
      const edited = { ...state.summary.output, followUps: ['Check the printer again on Monday'] };
      const v2 = await api.expect('PUT', `/api/v1/sessions/${state.sessionId}/summary`, { baseVersion: state.summary.version, output: edited });
      eq(v2.version, state.summary.version + 1, 'version');
      eq(v2.trigger, 'edit', 'trigger');
      const stale = await api.request('PUT', `/api/v1/sessions/${state.sessionId}/summary`, { baseVersion: state.summary.version, output: edited });
      eq(stale.json?.error?.code, 'summary_conflict', 'a stale base');
      const a = await api.expect('GET', `/api/v1/sessions/${state.sessionId}/audit`);
      check(a.items.some((e) => e.action === 'summary.edited'), 'missing summary.edited');
    });

    await run.step(
      'ai: push the summary to a webhook (when the tickets stream is present)',
      async () => {
        const put = await api.request('PUT', '/api/v1/integrations/webhook', { enabled: true, config: { url: `http://127.0.0.1:${port}/hook` } });
        if (put.status === 404) return 'not run: the tickets routes are not present on this api';
        if (put.status === 400 && put.json?.error?.code === 'egress_refused') return 'not run: start the api with EGRESS_ALLOW_HTTP=1 and EGRESS_ALLOW_LOOPBACK=1 to push to the local receiver';
        check(put.status === 200 || put.status === 201, `PUT /integrations/webhook -> ${put.status} ${put.json?.error?.code ?? ''}`);
        const push = await api.request('POST', '/api/v1/integrations/webhook/ticket', { sessionId: state.sessionId, clientPushId: randomUUID(), mode: 'create', source: 'summary' });
        check(push.status >= 200 && push.status < 300, `POST /integrations/webhook/ticket -> ${push.status} ${push.json?.error?.code ?? ''}`);
        return `push ${push.json?.push?.state ?? push.status}; receiver saw ${fake.seen.hooks.length}`;
      },
      { critical: false },
    );
  } finally {
    if (fake) await new Promise((r) => fake.server.close(() => r()));
  }
}
